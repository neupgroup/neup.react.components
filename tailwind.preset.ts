import type {Config} from 'tailwindcss';

// Resolve all palette steps from the active shared theme.
function palette(name: string) {
  return Object.fromEntries([0,10,20,30,40,50,100,200,300,400,500,600,700,800,900,950,960,970,980,990,1000].map(step => [step, `var(--${name}-${step})`]));
}

// Resolve interaction states without hardcoding a light surface.
function states(name: string) {
  return Object.fromEntries(['hover', 'press', 'active', 'active-hover', 'active-press'].map(state => [state, `var(--${name}-${state})`]));
}

